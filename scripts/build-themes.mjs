import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

// Add a theme in src/themes/themes.json with the same color roles. The Settings
// options, CSS palettes and first-paint script are all derived from that registry.
import { initializeTheme } from "../src/themes/runtime.mjs";
const root = new URL("../", import.meta.url);
export function buildThemes() {
  const themes = JSON.parse(
    readFileSync(new URL("src/themes/themes.json", root), "utf8")
  );
  const tokens = Object.keys(themes.light.colors).sort();
  const effects = Object.keys(themes.light.effects).sort();
  for (const [id, theme] of Object.entries(themes)) {
    if (
      !/^[a-z][a-z0-9-]*$/.test(id) ||
      id === "system" ||
      !["light", "dark"].includes(theme.colorScheme) ||
      JSON.stringify(Object.keys(theme.effects).sort()) !==
        JSON.stringify(effects) ||
      JSON.stringify(Object.keys(theme.colors).sort()) !==
        JSON.stringify(tokens)
    ) {
      throw new Error(`Theme ${id} must provide every semantic color token`);
    }
  }
  const declarations = (theme) =>
    `  color-scheme: ${theme.colorScheme};\n` +
    Object.entries(theme.effects)
      .map(([key, value]) => `  --${key}: ${value};\n`)
      .join("") +
    Object.entries(theme.colors)
      .map(([key, value]) => {
        const rgb = /^#[\da-f]{6}$/i.test(value)
          ? `\n  --${key}-rgb: ${[1, 3, 5]
              .map((i) => parseInt(value.slice(i, i + 2), 16))
              .join(" ")};`
          : "";
        return `  --${key}: ${value};${rgb}`;
      })
      .join("\n");
  const css =
    "/* Generated by scripts/build-themes.mjs from src/themes/themes.json. */\n" +
    Object.entries(themes)
      .map(
        ([id, theme]) =>
          `${
            id === "light" ? ":root, " : ""
          }:root[data-theme="${id}"] {\n${declarations(theme)}\n}`
      )
      .join("\n\n") +
    `\n@media (prefers-color-scheme: dark) {\n:root:not([data-theme]) {\n${declarations(
      themes.dark
    )}\n}\n}\n`;
  const metadata = Object.fromEntries(
    Object.entries(themes).map(([id, theme]) => [
      id,
      { colorScheme: theme.colorScheme },
    ])
  );
  const js = `/* Generated from src/themes/runtime.mjs. */\n(${initializeTheme.toString()})(${JSON.stringify(
    metadata
  )});\n`;
  writeFileSync(new URL("public/themes.css", root), css);
  writeFileSync(new URL("public/theme.js", root), js);
}
if (process.argv[1] === fileURLToPath(import.meta.url)) buildThemes();
